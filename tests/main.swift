import Foundation

func expect(_ condition: Bool, _ message: String) {
    precondition(condition, message)
}

expect(VoiceCue.resolve(bearing: 360, distance: 4) == .ahead, "Wrap heading")
expect(VoiceCue.resolve(bearing: -90, distance: 4) == .left, "Left")
expect(VoiceCue.resolve(bearing: 90, distance: 4) == .right, "Right")
expect(VoiceCue.resolve(bearing: -180, distance: 4) == .behind, "Behind")
expect(VoiceCue.resolve(bearing: 20, distance: 1.5) == .ahead, "Threshold boundary")
expect(VoiceCue.resolve(bearing: 90, distance: 1.49) == .arrived, "Arrival")
expect(VoiceCue.resolve(bearing: .nan, distance: 4) == nil, "Invalid bearing")
expect(VoiceCue.resolve(bearing: 0, distance: -1) == nil, "Invalid distance")

var scheduler = VoiceCueScheduler()
expect(scheduler.update(.ahead, now: 0) == nil, "Debounce initial cue")
expect(scheduler.update(.right, now: 0.5) == nil, "Ignore short-lived cue")
expect(scheduler.update(.right, now: 1.25) == .right, "Speak stable cue")
expect(scheduler.update(.left, now: 1.5) == nil, "Start new candidate")
expect(scheduler.update(.left, now: 2.25) == nil, "Rate limit direction changes")
expect(scheduler.update(.left, now: 4.25) == .left, "Speak latest direction")
expect(scheduler.update(.left, now: 16.25) == .left, "Repeat stationary guidance")
expect(scheduler.update(.arrived, now: 16.5) == .arrived, "Arrival takes priority")
expect(scheduler.update(.arrived, now: 40) == nil, "Do not repeat arrival")
expect(scheduler.update(nil, now: 41) == nil, "Reset invalid guidance")
expect(scheduler.update(.ahead, now: 42) == nil, "Debounce after reset")
expect(scheduler.update(.ahead, now: 43) == .ahead, "Resume after reset")
print("Voice cue and scheduling checks passed")

var haptics = OffCourseHaptics()
expect(haptics.update(bearing: 0, distance: 4, now: 0) == nil, "Silent on course")
expect(haptics.update(bearing: 44, distance: 4, now: 1) == nil, "Below subtle threshold")
expect(haptics.update(bearing: 45, distance: 4, now: 2) == nil, "Debounce subtle heading")
expect(haptics.update(bearing: 45, distance: 4, now: 2.75) == .subtle, "Subtle pulse at 45 degrees")
expect(haptics.update(bearing: 60, distance: 4, now: 3) == nil, "Rate limit subtle pulses")
expect(haptics.update(bearing: 60, distance: 4, now: 4.75) == .subtle, "Subtle repeats every two seconds")
expect(haptics.update(bearing: 100, distance: 4, now: 5) == nil, "Debounce escalation")
expect(haptics.update(bearing: 180, distance: 4, now: 5.75) == .strong, "Escalate to strong")
expect(haptics.update(bearing: -180, distance: 4, now: 6) == nil, "Rate limit strong pulses")
expect(haptics.update(bearing: -180, distance: 4, now: 6.5) == .strong, "Strong repeats every 0.75 seconds")
expect(haptics.update(bearing: 90, distance: 4, now: 7.25) == .strong, "Strong boundary hysteresis")
expect(haptics.update(bearing: 80, distance: 4, now: 8) == nil, "Downgrade on correction")
expect(haptics.update(bearing: 80, distance: 4, now: 9.25) == .subtle, "Resume subtle cadence")
expect(haptics.update(bearing: 31, distance: 4, now: 11.25) == .subtle, "Subtle boundary hysteresis")
expect(haptics.update(bearing: 30, distance: 4, now: 12) == nil, "Stop on correction without success haptic")
expect(haptics.update(bearing: 405, distance: 4, now: 13) == nil, "Wrap heading")
expect(haptics.update(bearing: 44, distance: 4, now: 13.75) == .subtle, "Stable near subtle boundary")
expect(haptics.update(bearing: 180, distance: 1.49, now: 15) == nil, "Silent at arrival")
expect(haptics.update(bearing: .nan, distance: 4, now: 16) == nil, "Silent for invalid heading")
expect(haptics.update(bearing: 180, distance: .infinity, now: 17) == nil, "Silent for invalid distance")
expect(haptics.update(bearing: 180, distance: -1, now: 18) == nil, "Silent for negative distance")
expect(haptics.update(bearing: -100, distance: 4, now: 19) == nil, "Fresh debounce after invalid data")
expect(haptics.update(bearing: -100, distance: 4, now: 19.75) == .strong, "Symmetric strong threshold")
haptics.reset()
expect(haptics.update(bearing: -45, distance: 4, now: 20) == nil, "Fresh debounce after lifecycle reset")
expect(haptics.update(bearing: -45, distance: 4, now: 20.75) == .subtle, "Symmetric subtle threshold")
haptics.reset()
expect(haptics.update(bearing: 100, distance: 4, now: 21) == nil, "Begin brief deviation")
expect(haptics.update(bearing: 0, distance: 4, now: 21.5) == nil, "Ignore brief deviation")
expect(haptics.update(bearing: 100, distance: 4, now: 22) == nil, "Restart debounce")
expect(haptics.update(bearing: 100, distance: 4, now: 22.75) == .strong, "Sustained deviation after noise")
print("Two-strength off-course haptic checks passed")

expect(NavigationAccess.permitsStart(verified: true, manualTest: false), "Verified navigation allowed")
expect(!NavigationAccess.permitsStart(verified: false, manualTest: false), "Unverified navigation requires opt-in")
#if DEBUG
expect(NavigationAccess.permitsStart(verified: false, manualTest: true), "Manual test available in developer build")
#else
expect(!NavigationAccess.permitsStart(verified: false, manualTest: true), "Release build cannot bypass verification")
#endif
print("Navigation access checks passed")
